/// `BenchUtils::make_big_path()`.
// Port of: bench/BigPath.cpp#L19-L5170 (chrome/m156)
fn make_big_path() -> Path {
    // SkPathBuilder path;
    let mut path = PathBuilder::new();
    for step in BIG_PATH_STEPS {
        match *step {
            Step::Move(x, y) => {
                path.move_to((x, y));
            }
            Step::Line(x, y) => {
                path.line_to((x, y));
            }
            Step::Cubic(x1, y1, x2, y2, x3, y3) => {
                path.cubic_to((x1, y1), (x2, y2), (x3, y3));
            }
        }
    }
    // return path.detach();
    path.detach()
}

