//! `cargo xtask text-deps break-data [--check]`: regenerates `crates/skia-rust-unicode-data` (the
//! break data of Chromium's ICU, milestone M4 of `docs/design/modules.md` §9 and §3.6) from
//! `common/icudtl.dat` at the pin of `inventory/text-deps.lock` `[icu]`.
//!
//! The crate holds the `brkitr/*.brk` rule tables and `brkitr/*.dict` dictionaries of that file,
//! byte for byte (they are what Chromium's ICU loads at run time, built from `source/data/brkitr`
//! with Chromium's `patches/`), and `src/generated.rs`, which names them and records their
//! SHA-256. Run it after bumping the ICU pin; `--check` fails if the committed crate differs.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, anyhow, bail, ensure};

const CRATE: &str = "crates/skia-rust-unicode-data";

/// The entries of an ICU common data package (`udata.cpp` `offsetTOCLookupFn` layout): a
/// `MappedData` header, then `count` and `count` pairs of (name offset, data offset), both
/// relative to the table of contents. Returns `(name, bytes)` in TOC order.
fn toc(data: &[u8]) -> Result<Vec<(String, &[u8])>> {
    let u16_at = |i: usize| -> Result<u16> {
        Ok(u16::from_le_bytes(
            data.get(i..i + 2).context("short header")?.try_into()?,
        ))
    };
    let u32_at = |i: usize| -> Result<usize> {
        Ok(u32::from_le_bytes(data.get(i..i + 4).context("short TOC")?.try_into()?) as usize)
    };
    ensure!(
        data.get(2..4) == Some(&[0xda, 0x27][..]),
        "not an ICU data file"
    );
    // UDataInfo.isBigEndian.
    ensure!(data.get(8) == Some(&0), "icudtl.dat is not little-endian");
    let toc = usize::from(u16_at(0)?);
    let count = u32_at(toc)?;
    let mut entries = Vec::with_capacity(count);
    for i in 0..count {
        let name_at = toc + u32_at(toc + 4 + 8 * i)?;
        let data_at = toc + u32_at(toc + 8 + 8 * i)?;
        let end = data[name_at..]
            .iter()
            .position(|&b| b == 0)
            .context("unterminated name")?;
        let name = std::str::from_utf8(&data[name_at..name_at + end])?.to_owned();
        entries.push((name, data_at));
    }
    let mut out = Vec::with_capacity(count);
    for (i, (name, start)) in entries.iter().enumerate() {
        let end = entries.get(i + 1).map_or(data.len(), |e| e.1);
        out.push((name.clone(), &data[*start..end]));
    }
    Ok(out)
}

/// The generated module.
fn generated(rev: &str, files: &[(String, Vec<u8>)]) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// @generated by `cargo xtask text-deps break-data` from Chromium ICU {rev}\n\
         // (`common/icudtl.dat`, `brkitr/`). Do not edit.\n"
    );
    let _ = writeln!(
        s,
        "/// The Chromium ICU revision the data comes from (`inventory/text-deps.lock` `[icu]`).\n\
         pub const ICU_REVISION: &str = \"{rev}\";\n"
    );
    for (ext, func, what) in [
        (
            "brk",
            "rule_file",
            "The compiled rule file `brkitr/<name>.brk` (an `RBBIDataHeader` behind ICU's data\n\
             /// header), or `None` when Chromium's data has no such file.",
        ),
        (
            "dict",
            "dictionary",
            "The dictionary `brkitr/<name>.dict` (`DictionaryData` indexes and a string trie behind\n\
             /// ICU's data header), or `None` when Chromium's data has no such file.",
        ),
    ] {
        let _ = writeln!(s, "/// {what}");
        let _ = writeln!(s, "#[must_use]");
        let _ = writeln!(s, "pub fn {func}(name: &str) -> Option<&'static [u8]> {{");
        let _ = writeln!(s, "    match name {{");
        for (file, bytes) in files {
            if let Some(stem) = file.strip_suffix(&format!(".{ext}")) {
                let _ = writeln!(
                    s,
                    "        // {} bytes, SHA-256 {}",
                    bytes.len(),
                    skia_rust_text_deps::sha256_hex(bytes)
                );
                let _ = writeln!(
                    s,
                    "        \"{stem}\" => Some(include_bytes!(\"data/{file}\")),"
                );
            }
        }
        let _ = writeln!(s, "        _ => None,");
        let _ = writeln!(s, "    }}");
        let _ = writeln!(s, "}}\n");
    }
    let _ = writeln!(
        s,
        "/// Every file: `(name with extension, SHA-256 of its bytes)`.\n\
         pub const FILES: &[(&str, &str)] = &["
    );
    for (file, bytes) in files {
        let _ = writeln!(
            s,
            "    (\n        \"{file}\",\n        \"{}\",\n    ),",
            skia_rust_text_deps::sha256_hex(bytes)
        );
    }
    let _ = writeln!(s, "];");
    s
}

pub fn run(root: &Path, check: bool) -> Result<()> {
    let icu = skia_rust_text_deps::icu().map_err(|e| anyhow!(e))?;
    let lock = skia_rust_text_deps::Lock::read("text-deps.lock").map_err(|e| anyhow!(e))?;
    let rev = lock.get("icu", "rev").map_err(|e| anyhow!(e))?.to_owned();
    let dat = std::fs::read(&icu.data).with_context(|| icu.data.display().to_string())?;
    let mut files: Vec<(String, Vec<u8>)> = Vec::new();
    for (name, bytes) in toc(&dat)? {
        // `icudt78l/brkitr/word.brk`: the package name, the tree, the item.
        let mut parts = name.splitn(3, '/');
        let (_, tree, item) = (parts.next(), parts.next(), parts.next());
        if tree != Some("brkitr") {
            continue;
        }
        let Some(item) = item else { continue };
        let ext = Path::new(item).extension().and_then(|e| e.to_str());
        if matches!(ext, Some("brk" | "dict")) {
            files.push((item.to_owned(), bytes.to_vec()));
        }
    }
    ensure!(
        !files.is_empty(),
        "no brkitr data in {}",
        icu.data.display()
    );
    files.sort();
    let dir = root.join(CRATE).join("src");
    let data_dir = dir.join("data");
    let module = generated(&rev, &files);
    if check {
        let mut stale = Vec::new();
        for (file, bytes) in &files {
            if std::fs::read(data_dir.join(file)).ok().as_deref() != Some(bytes.as_slice()) {
                stale.push(file.clone());
            }
        }
        if std::fs::read_to_string(dir.join("generated.rs")).ok() != Some(module) {
            stale.push(String::from("generated.rs"));
        }
        for entry in std::fs::read_dir(&data_dir)? {
            let name = entry?.file_name().to_string_lossy().into_owned();
            let known = files.iter().any(|(f, _)| *f == name);
            if !known && name != "LICENSE" {
                stale.push(format!("{name} (not in icudtl.dat)"));
            }
        }
        if !stale.is_empty() {
            bail!(
                "{CRATE} is not current for ICU {rev}: {stale:?}\n\
                 Run `cargo xtask text-deps break-data`."
            );
        }
        println!("{CRATE} is current ({} files, ICU {rev})", files.len());
        return Ok(());
    }
    std::fs::create_dir_all(&data_dir)?;
    for entry in std::fs::read_dir(&data_dir)? {
        let path = entry?.path();
        let name = path.file_name().map(|n| n.to_string_lossy().into_owned());
        if name.as_deref() != Some("LICENSE") {
            std::fs::remove_file(&path)?;
        }
    }
    let mut total = 0;
    for (file, bytes) in &files {
        std::fs::write(data_dir.join(file), bytes)?;
        total += bytes.len();
        println!("{file:32} {:>9}", bytes.len());
    }
    std::fs::write(dir.join("generated.rs"), module)?;
    println!("{} files, {total} bytes, ICU {rev}", files.len());
    Ok(())
}
