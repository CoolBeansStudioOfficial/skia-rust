//! `cargo xtask oracle unicode-diff`: Chromium's ICU 78.2 at Skia's pin against ICU4X and
//! `unicode-bidi` (`oracle/unicode-diff`, `docs/design/modules.md` §3.3).
//!
//! * No flag: fetch ICU and the UAX conformance files (`cargo xtask text-deps fetch`), build the C++
//!   driver (about 150 s on 4 cores; the objects are cached in `target/unicode-diff`), run it over the
//!   corpus and check that its output still equals `oracle/unicode-diff/expected/*.txt`.
//! * `--update`: replace the expected files with the driver's output.
//! * `--replay`: only run the Rust twin against the stored results (any host, no C++): what
//!   `cargo test -p skia-rust-unicode-diff` does, with a report.
//!
//! Needs a Linux/macOS host with `g++` for the C++ side.

// `ICU4X` and `Chromium` are proper names, not code.
#![allow(clippy::doc_markdown)]

use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, anyhow, bail};

/// Options of the command.
pub struct Options {
    /// Rewrite the expected files.
    pub update: bool,
    /// Only replay the stored results against the Rust twin.
    pub replay: bool,
}

/// The driver's sections, which are also the expected files' stems.
const SECTIONS: [&str; 7] = [
    "breaks",
    "bidi",
    "reorder",
    "props",
    "case",
    "conformance",
    "misc",
];

fn run(cmd: &mut Command) -> Result<String> {
    let out = cmd.output().with_context(|| format!("running {cmd:?}"))?;
    if !out.status.success() {
        bail!(
            "{cmd:?} failed ({}): {}",
            out.status,
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

fn header() -> &'static str {
    "# Generated by `cargo xtask oracle unicode-diff --update` from oracle/unicode-diff/cpp/unicode_diff.cc (Chromium ICU 78.2, d578f2e8); do not edit.\n"
}

fn replay(root: &Path, cargo: &str) -> Result<()> {
    let out = Command::new(cargo)
        .args([
            "run",
            "--release",
            "-p",
            "skia-rust-unicode-diff",
            "--",
            "check",
        ])
        .current_dir(root)
        .output()
        .context("running unicode-diff check")?;
    print!("{}", String::from_utf8_lossy(&out.stdout));
    if !out.status.success() {
        bail!("replay failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    Ok(())
}

pub fn run_command(root: &Path, opts: &Options) -> Result<()> {
    let dir = root.join("oracle").join("unicode-diff");
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
    if opts.replay {
        return replay(root, &cargo);
    }
    if cfg!(windows) {
        bail!("the C++ side needs g++ on Linux or macOS; use --replay here");
    }
    let icu = skia_rust_text_deps::icu().map_err(|e| anyhow!(e))?;
    let ucd = skia_rust_text_deps::ucd().map_err(|e| anyhow!(e))?;
    let work = root.join("target").join("unicode-diff");
    std::fs::create_dir_all(&work)?;
    let driver = work.join("unicode_diff");
    run(Command::new("sh")
        .arg(dir.join("build.sh"))
        .arg(&icu.common)
        .arg(&driver))?;
    println!("built {}", driver.display());

    let mut failures = 0;
    for section in SECTIONS {
        let mut text = header().to_owned();
        text += &run(Command::new(&driver)
            .arg("--data")
            .arg(&icu.data)
            .arg("--corpus")
            .arg(dir.join("corpus"))
            .arg("--ucd")
            .arg(&ucd)
            .arg(section))?;
        let path = dir.join("expected").join(format!("{section}.txt"));
        if opts.update {
            std::fs::create_dir_all(dir.join("expected"))?;
            std::fs::write(&path, &text)?;
            println!("wrote {}", path.display());
        } else if std::fs::read_to_string(&path)? == text {
            println!(
                "{section}: expected file is current ({} lines)",
                text.lines().filter(|l| !l.starts_with('#')).count()
            );
        } else {
            println!("{section}: DIFFERS from {}", path.display());
            failures += 1;
        }
    }
    if failures > 0 {
        bail!(
            "{failures} expected file(s) are stale: rerun with --update, then update known-divergences.txt with oracle/unicode-diff/classify.py"
        );
    }
    Ok(())
}
