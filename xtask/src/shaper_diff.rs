//! `cargo xtask oracle shaper-diff`: HarfBuzz at Skia's pin against HarfRust
//! (`oracle/shaper-diff`, `docs/design/modules.md` §2.4).
//!
//! * No flag: fetch HarfBuzz (`cargo xtask text-deps fetch`), build the C++ driver, run it over
//!   the corpus and check that its output still equals `oracle/shaper-diff/expected/*.txt`.
//! * `--update`: replace the expected files with the driver's output.
//! * `--replay`: only run the Rust side against the stored results (any host, no C++): what
//!   `cargo test -p skia-rust-shaper-diff` does, with a report.
//!
//! Needs a Linux/macOS host with `g++` for the C++ side.

// `HarfBuzz` and `HarfRust` are proper names, not code.
#![allow(clippy::doc_markdown)]

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, anyhow, bail};

/// Options of the command.
pub struct Options {
    /// Rewrite the expected files.
    pub update: bool,
    /// Only replay the stored results against HarfRust.
    pub replay: bool,
}

const MODES: [(&str, &str); 3] = [("a", "builtin"), ("b", "skia-funcs"), ("c", "empty-face")];

fn run(cmd: &mut Command) -> Result<String> {
    let out = cmd.output().with_context(|| format!("running {cmd:?}"))?;
    if !out.status.success() {
        bail!(
            "{cmd:?} failed ({}): {}",
            out.status,
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

fn header(file: &str) -> String {
    let what = match file {
        "builtin" => "mode a: HarfBuzz 9cb1fee5 with its own OpenType font functions",
        "skia-funcs" => {
            "mode b: HarfBuzz 9cb1fee5 with Skia's font functions (SkShaper_harfbuzz.cpp#L72-L238)"
        }
        _ => {
            "mode c: HarfBuzz 9cb1fee5, empty face (no tables, upem 2048) with synthetic callbacks"
        }
    };
    format!(
        "# Generated by `cargo xtask oracle shaper-diff --update` from oracle/shaper-diff/cpp/shaper_diff.cc; do not edit.\n# {what}\n# config font source lines glyphs sha256\n"
    )
}

fn replay(root: &Path, cargo: &str) -> Result<()> {
    let out = Command::new(cargo)
        .args([
            "run",
            "--release",
            "-p",
            "skia-rust-shaper-diff",
            "--",
            "check",
        ])
        .current_dir(root)
        .output()
        .context("running shaper-diff check")?;
    print!("{}", String::from_utf8_lossy(&out.stdout));
    if !out.status.success() {
        bail!("replay failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    Ok(())
}

// The steps are sequential and share their paths; splitting them would only add plumbing.
#[allow(clippy::too_many_lines)]
pub fn run_command(root: &Path, opts: &Options) -> Result<()> {
    let dir = root.join("oracle").join("shaper-diff");
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
    if opts.replay {
        return replay(root, &cargo);
    }
    if cfg!(windows) {
        bail!("the C++ side needs g++ on Linux or macOS; use --replay here");
    }
    let hb = skia_rust_text_deps::harfbuzz().map_err(|e| anyhow!(e))?;
    let work = root.join("target").join("shaper-diff");
    std::fs::create_dir_all(&work)?;
    let driver = work.join("shaper_diff");
    run(Command::new("sh")
        .arg(dir.join("build.sh"))
        .arg(skia_rust_text_deps::harfbuzz_src(&hb))
        .arg(&driver))?;
    println!("built {}", driver.display());

    let fonts: PathBuf =
        match std::env::var_os("SKIA_RUST_SHAPER_DIFF_FONTS").filter(|v| !v.is_empty()) {
            Some(d) => PathBuf::from(d),
            None => skia_rust_text_deps::test_fonts().map_err(|e| anyhow!(e))?,
        };
    let tables = work.join("tables");
    println!(
        "{}",
        run(Command::new(&cargo)
            .args([
                "run",
                "--release",
                "-q",
                "-p",
                "skia-rust-shaper-diff",
                "--",
                "tables"
            ])
            .arg(&tables)
            .env("SKIA_RUST_SHAPER_DIFF_FONTS", &fonts)
            .current_dir(root))?
        .trim()
    );

    let mut configs = Vec::new();
    for line in std::fs::read_to_string(dir.join("configs.txt"))?.lines() {
        let f: Vec<&str> = line.split_whitespace().collect();
        if f.len() == 4 && !line.starts_with('#') {
            configs.push((f[0].to_owned(), f[1].to_owned()));
        }
    }
    let mut failures = 0;
    for (letter, file) in MODES {
        let mut text = header(file);
        for (name, mode) in &configs {
            if mode != letter {
                continue;
            }
            text += &run(Command::new(&driver)
                .arg("--fonts")
                .arg(&fonts)
                .arg("--font-list")
                .arg(dir.join("fonts.txt"))
                .arg("--configs")
                .arg(dir.join("configs.txt"))
                .arg("--corpus")
                .arg(dir.join("corpus"))
                .arg("--tables")
                .arg(&tables)
                .args(["--config", name]))?;
        }
        let path = dir.join("expected").join(format!("{file}.txt"));
        if opts.update {
            std::fs::create_dir_all(dir.join("expected"))?;
            std::fs::write(&path, &text)?;
            println!("wrote {}", path.display());
        } else if std::fs::read_to_string(&path)? == text {
            println!(
                "{file}: expected file is current ({} rows)",
                text.lines().filter(|l| !l.starts_with('#')).count()
            );
        } else {
            println!("{file}: DIFFERS from {}", path.display());
            failures += 1;
        }
    }
    if failures > 0 {
        bail!(
            "{failures} expected file(s) are stale: rerun with --update, then update known-divergences.txt with oracle/shaper-diff/classify.py"
        );
    }
    Ok(())
}
