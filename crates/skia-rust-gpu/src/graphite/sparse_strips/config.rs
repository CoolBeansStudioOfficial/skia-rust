//! [`SparseStripConfig`]: the compile-time parameters of sparse strips rendering.

use skia_rust_core::color_type::ColorType;

/// Tunable compile-time parameters that control various aspects of sparse strips behavior.
// Port of: src/gpu/graphite/sparse_strips/SparseStripsConfig.h#L16-L60 (chrome/m156)
#[doc(alias = "skgpu::graphite::SparseStripConfig")]
#[derive(Clone, Copy, Debug)]
pub struct SparseStripConfig;

impl SparseStripConfig {
    /// `kTileWidth`: the width, in pixels, of the tiles generated by polylines.
    pub const K_TILE_WIDTH: u16 = 8;
    /// `kTileHeight`: the height, in pixels, of the tiles generated by polylines.
    pub const K_TILE_HEIGHT: u16 = 8;

    /// `kColorType`: the color type of the alpha atlas.
    pub const K_COLOR_TYPE: ColorType = ColorType::RGBA8888;
    /// `kAtlasBytesPerTexel`.
    pub const K_ATLAS_BYTES_PER_TEXEL: i32 = 4;

    /// `kAtlasWidth`.
    pub const K_ATLAS_WIDTH: i32 = 8192;
    /// `kAtlasWidthBytes`.
    pub const K_ATLAS_WIDTH_BYTES: i32 = Self::K_ATLAS_WIDTH * Self::K_ATLAS_BYTES_PER_TEXEL;
    /// `kInitialAtlasRows`.
    pub const K_INITIAL_ATLAS_ROWS: i32 = 1;
    /// `kMaxAtlasRows`.
    pub const K_MAX_ATLAS_ROWS: i32 = 8192;
    /// `kMaxAtlasBytes`.
    pub const K_MAX_ATLAS_BYTES: i32 =
        Self::K_ATLAS_WIDTH * Self::K_MAX_ATLAS_ROWS * Self::K_ATLAS_BYTES_PER_TEXEL;
    /// `kMaxTexturePages`.
    pub const K_MAX_TEXTURE_PAGES: i32 = 2;

    /// `kNumSubSamples`: the number of MSAA subsamples in sparse strips rendering. Only 8 is
    /// supported.
    pub const K_NUM_SUB_SAMPLES: i32 = 8;

    /// `kLutMaskWidth`.
    pub const K_LUT_MASK_WIDTH: i32 = 64;
    /// `kLutMaskHeight`.
    pub const K_LUT_MASK_HEIGHT: i32 = 64;
    /// `kLutMaskWidthExcl`.
    pub const K_LUT_MASK_WIDTH_EXCL: i32 = Self::K_LUT_MASK_WIDTH - 1;
    /// `kLutMaskHeightExcl`.
    pub const K_LUT_MASK_HEIGHT_EXCL: i32 = Self::K_LUT_MASK_HEIGHT - 1;
    /// `kLutMaskWidthF`.
    #[allow(clippy::cast_precision_loss)] // 64 is exact in f32
    pub const K_LUT_MASK_WIDTH_F: f32 = Self::K_LUT_MASK_WIDTH as f32;
    /// `kLutMaskHeightF`.
    #[allow(clippy::cast_precision_loss)] // 64 is exact in f32
    pub const K_LUT_MASK_HEIGHT_F: f32 = Self::K_LUT_MASK_HEIGHT as f32;

    /// `kStripEpsilon`.
    pub const K_STRIP_EPSILON: f32 = 1e-5;
}

// The tile dimensions MUST match the hard coded constant in the fragment shader. If that value
// changes, this must be updated.
const _: () = assert!(SparseStripConfig::K_TILE_WIDTH == SparseStripConfig::K_TILE_HEIGHT);
const _: () = assert!(SparseStripConfig::K_TILE_WIDTH == 8);
// The AlphaAtlasManager uses a flipflopping allocation system that will break if the page count
// is increased beyond 2.
const _: () = assert!(SparseStripConfig::K_MAX_TEXTURE_PAGES == 2);
// To avoid uploading the texture width, and to avoid a costly divide and mod in the shader, we
// assume that the atlas width is always fixed.
const _: () = assert!(SparseStripConfig::K_ATLAS_WIDTH == 8192);
const _: () =
    assert!(SparseStripConfig::K_NUM_SUB_SAMPLES & (SparseStripConfig::K_NUM_SUB_SAMPLES - 1) == 0);
