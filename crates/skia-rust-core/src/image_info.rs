/// Describes color range of YUV pixels. The color mapping from YUV to RGB varies depending on the
/// source. YUV pixels may be generated by JPEG images, standard video streams, or high definition
/// video streams. Each has its own mapping from YUV to RGB.
///
/// JPEG YUV values encode the full range of 0 to 255 for all three components. Video YUV values
/// often range from 16 to 235 for Y and from 16 to 240 for U and V (limited). Details of encoding
/// and conversion to RGB are described in YCbCr color space.
///
/// The identity colorspace exists to provide a utility mapping from Y to R, U to G and V to B. It
/// can be used to visualize the YUV planes or to explicitly post process the YUV channels.
// Port of: include/core/SkImageInfo.h#L68-L106 (chrome/m156)
#[doc(alias = "SkYUVColorSpace")]
#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]
