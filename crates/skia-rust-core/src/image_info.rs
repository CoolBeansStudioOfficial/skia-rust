/// Describes pixel dimensions and encoding. [`Bitmap`](crate::bitmap::Bitmap), `Image`,
/// [`Pixmap`](crate::pixmap::Pixmap), and `Surface` can be created from [`ImageInfo`].
/// [`ImageInfo`] can be retrieved from `Bitmap` and `Pixmap`, but not from `Image` and `Surface`.
/// For example, `Image` and `Surface` implementations may defer pixel depth, so may not
/// completely specify [`ImageInfo`].
///
/// [`ImageInfo`] contains dimensions, the pixel integral width and height. It encodes how pixel
/// bits describe alpha, transparency; color components red, blue, and green; and [`ColorSpace`],
/// the range and linearity of colors.
// Port of: include/core/SkImageInfo.h#L214-L627 (chrome/m156)
#[doc(alias = "SkImageInfo")]
#[derive(Clone, Debug, Default)]
pub struct ImageInfo {
    color_info: ColorInfo,
    dimensions: ISize,
}

/// `SkImageInfo::operator==`: dimensions, color type, alpha type and color space are equivalent.
// Port of: include/core/SkImageInfo.h#L551-L553 (chrome/m156)
impl PartialEq for ImageInfo {
    fn eq(&self, other: &Self) -> bool {
        self.dimensions == other.dimensions && self.color_info == other.color_info
    }
}

