//! `SkUnPreMultiply`: converts premultiplied colors back to unpremultiplied ones.

use crate::color::{Color, PMColor};
use crate::color_priv::{get_packed_a32, get_packed_b32, get_packed_g32, get_packed_r32};
use crate::math::U8CPU;

/// Fixed-point (8.24) reciprocal-of-alpha scale factor.
// Port of: include/core/SkUnPreMultiply.h#L19 (chrome/m156)
#[doc(alias = "SkUnPreMultiply::Scale")]
pub type Scale = u32;

/// Returns the table of scale factors, indexed by alpha `[0..255]`.
// Port of: include/core/SkUnPreMultiply.h#L22-L24 (chrome/m156)
#[doc(alias = "SkUnPreMultiply::GetScaleTable")]
#[must_use]
pub fn get_scale_table() -> &'static [Scale; 256] {
    &TABLE
}

/// Returns the scale factor for `alpha`.
// Port of: include/core/SkUnPreMultiply.h#L26-L29 (chrome/m156)
#[doc(alias = "SkUnPreMultiply::GetScale")]
#[must_use]
pub fn get_scale(alpha: U8CPU) -> Scale {
    debug_assert!(alpha <= 255);
    TABLE[alpha as usize]
}

/// Applies `scale` to a premultiplied `component`, yielding the unpremultiplied value.
// Port of: include/core/SkUnPreMultiply.h#L47-L50 (chrome/m156)
#[doc(alias = "SkUnPreMultiply::ApplyScale")]
#[must_use]
pub fn apply_scale(scale: Scale, component: U8CPU) -> U8CPU {
    debug_assert!(component <= 255);
    scale.wrapping_mul(component).wrapping_add(1 << 23) >> 24
}

/// Converts a premultiplied color to an unpremultiplied [`Color`].
// Port of: src/core/SkUnPreMultiply.cpp#L11-L19 (chrome/m156)
#[doc(alias = "SkUnPreMultiply::PMColorToColor")]
#[must_use]
#[allow(clippy::cast_possible_truncation)] // SkColorSetARGB takes U8CPU; each value is <= 255
pub fn pm_color_to_color(c: PMColor) -> Color {
    let a = get_packed_a32(c);
    let scale = get_scale(a);
    Color::from_argb(
        a as u8,
        apply_scale(scale, get_packed_r32(c)) as u8,
        apply_scale(scale, get_packed_g32(c)) as u8,
        apply_scale(scale, get_packed_b32(c)) as u8,
    )
}

