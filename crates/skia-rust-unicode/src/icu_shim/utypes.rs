// Port of: icu4c/source/common/utypes.cpp#L210-L232 (chromium/deps/icu d578f2e8)
/// `u_errorName(code)`: the name of a `UErrorCode`, or `[BOGUS UErrorCode]`.
#[doc(alias = "u_errorName")]
#[must_use]
pub fn u_error_name(code: UErrorCode) -> &'static str {
    // The ranges of `utypes.h`: the base of each table and the table.
    let tables: [(i32, &[&'static str]); 8] = [
        (0, &ERROR_NAME),
        (-128, &ERROR_INFO_NAME),
        (0x10000, &TRANS_ERROR_NAME),
        (0x10100, &FMT_ERROR_NAME),
        (0x10200, &BRK_ERROR_NAME),
        (0x10300, &REGEX_ERROR_NAME),
        (0x10400, &IDNA_ERROR_NAME),
        (0x10500, &PLUGIN_ERROR_NAME),
    ];
    for (start, names) in tables {
        if let Some(i) = code
            .checked_sub(start)
            .and_then(|i| usize::try_from(i).ok())
            .filter(|&i| i < names.len())
        {
            return names[i];
        }
    }
    "[BOGUS UErrorCode]"
}
