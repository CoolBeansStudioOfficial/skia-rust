// Port of: tests/PDFJpegEmbedTest.cpp#L26-L38 (chrome/m156)
fn is_subset_of(smaller: &[u8], larger: &[u8]) -> bool {
    if smaller.len() > larger.len() {
        return false;
    }
    let size = smaller.len();
    let size_diff = larger.len() - size;
    for i in 0..=size_diff {
        if larger[i..i + size] == *smaller {
            return true;
        }
    }
    false
}

// Port of: tests/PDFJpegEmbedTest.cpp#L41-L48 (chrome/m156)
fn load_resource(r: &mut Reporter, test: &str, filename: &str) -> Option<Data> {
    let data = get_resource_as_data(filename);
    if data.is_none() {
        infof!(r, "\n{}: Resource '{}' can not be found.\n", test, filename);
    }
    data.map(|bytes| Data::new_from_vec(bytes)) // May return None.
}

// Test that for Jpeg files that use the JFIF colorspace, they are
// directly embedded into the PDF (without re-encoding) when that
// makes sense.
// Port of: tests/PDFJpegEmbedTest.cpp#L50-L112 (chrome/m156)
def_test!(SkPDF_JpegEmbedTest, |r| {
    let test = "SkPDF_JpegEmbedTest";
    let mandrill_data = load_resource(r, test, "images/mandrill_512_q075.jpg");
    let cmyk_data = load_resource(r, test, "images/CMYK.jpg");
    let yuv_icc_data = load_resource(r, test, "images/crbug999986.jpeg");
    let cmyk_icc_data = load_resource(r, test, "images/crbug1465627.jpeg");

    let (Some(mandrill_data), Some(cmyk_data), Some(yuv_icc_data), Some(cmyk_icc_data)) =
        (mandrill_data, cmyk_data, yuv_icc_data, cmyk_icc_data)
    else {
        reporter_assert!(r, false, "Could not load all images");
        return;
    };
    ////////////////////////////////////////////////////////////////////////////
    let mut pdf = DynamicMemoryWStream::new();
    {
        let mut document = new_document(&mut pdf, Some(&jpeg::metadata_with_callbacks()));
        let canvas = document.begin_page(642.0, 2048.0, None).expect("a canvas");

        canvas.clear(skia_rust_core::color::Color4f::from_color(Color::new(0xFFCC_CCCC)));
        canvas.clip_irect(IRect::new(0, 0, 642, 2048), None);

        let im1 = deferred_from_encoded_data(Some(mandrill_data), None);
        canvas.draw_image(im1.expect("an image"), (65.0, 0.0), None);
        let im2 = deferred_from_encoded_data(Some(cmyk_data.clone()), None);
        canvas.draw_image(im2.expect("an image"), (0.0, 512.0), None);

        // This should be the same blue as the dark spot seen in the image.
        let mut blue_paint = Paint::default();
        blue_paint.set_color(Color::from_argb(255, 0, 59, 103));
        canvas.draw_rect(Rect::from_xywh(0.0, 1000.0, 642.0, 24.0), &blue_paint);
        let im3 = deferred_from_encoded_data(Some(yuv_icc_data.clone()), None);
        canvas.draw_image_rect_with_sampling_options(
            im3.expect("an image"),
            Some((
                &Rect::from_xywh(0.0, 0.0, 1024.0, 800.0),
                SrcRectConstraint::Fast,
            )),
            Rect::from_xywh(0.0, 1024.0, 1024.0, 800.0),
            SamplingOptions::default(),
            &Paint::default(),
        );

        let im4 = deferred_from_encoded_data(Some(cmyk_icc_data), None);
        canvas.draw_image(im4.expect("an image"), (0.0, 1536.0), None);

        document.end_page();
        document.close();
    }
    let pdf_data = pdf.detach_as_vector();

    // This JPEG uses a nonstandard colorspace - it can not be
    // embedded into the PDF directly.
    reporter_assert!(r, !is_subset_of(cmyk_data.as_bytes(), &pdf_data));

    // Part of this JPEG was drawn with drawImageRect.
    // However, the original data is smaller than the subset data so the original should be present.
    reporter_assert!(r, is_subset_of(yuv_icc_data.as_bytes(), &pdf_data));
});

/// `SkJFIFInfo::Type`.
// Port of: tests/PDFJpegEmbedTest.cpp#L114-L123 (chrome/m156)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum JfifType {
    Grayscale,
    YCbCr,
}

/// `SkJFIFInfo`.
#[derive(Debug, Clone, Copy)]
struct JfifInfo {
    size: ISize,
    ty: JfifType,
}

// Port of: tests/PDFJpegEmbedTest.cpp#L124-L146 (SkIsJFIF, chrome/m156)
fn is_jfif(data: Option<&[u8]>, info: Option<&mut JfifInfo>) -> bool {
    let jpeg_decoder = *decoders()
        .iter()
        .find(|d| d.id == "jpeg")
        .expect("a jpeg decoder");

    let Some(data) = data else {
        return false;
    };
    let Ok(codec) = Codec::make_from_stream(
        Box::new(MemoryStream::from_data(Some(Data::new_copy(data)))),
        &[jpeg_decoder],
    ) else {
        return false;
    };

    let jpeg_size = codec.dimensions();
    let jpeg_color_type = codec.encoded_info().color();
    let exif_orientation = codec.origin();

    let yuv = jpeg_color_type == EncodedColor::YUV;
    let good_color_type = yuv || jpeg_color_type == EncodedColor::Gray;
    if good_color_type && EncodedOrigin::TopLeft == exif_orientation {
        if let Some(info) = info {
            *info = JfifInfo {
                size: jpeg_size,
                ty: if yuv {
                    JfifType::YCbCr
                } else {
                    JfifType::Grayscale
                },
            };
        }
        return true;
    }
    false
}

