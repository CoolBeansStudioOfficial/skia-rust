// Port of: tests/PDFJpegEmbedTest.cpp#L148-L (chrome/m156)
def_test!(SkPDF_JpegIdentification, |r| {
    struct Test {
        path: &'static str,
        is_jfif: bool,
        ty: JfifType,
    }
    let k_tests = [
        Test {
            path: "images/CMYK.jpg",
            is_jfif: false,
            ty: JfifType::Grayscale,
        },
        Test {
            path: "images/color_wheel.jpg",
            is_jfif: true,
            ty: JfifType::YCbCr,
        },
        Test {
            path: "images/grayscale.jpg",
            is_jfif: true,
            ty: JfifType::Grayscale,
        },
        Test {
            path: "images/mandrill_512_q075.jpg",
            is_jfif: true,
            ty: JfifType::YCbCr,
        },
        Test {
            path: "images/randPixels.jpg",
            is_jfif: true,
            ty: JfifType::YCbCr,
        },
    ];
    for test in &k_tests {
        let Some(data) = load_resource(r, "JpegIdentification", test.path) else {
            continue;
        };
        let mut info = JfifInfo {
            size: ISize::new(0, 0),
            ty: JfifType::Grayscale,
        };
        let is_jfif_result = is_jfif(Some(data.as_bytes()), Some(&mut info));
        if is_jfif_result != test.is_jfif {
            errorf!(r, "{} failed isJfif test", test.path);
            continue;
        }
        if !is_jfif_result {
            continue; // not applicable
        }
        if test.ty != info.ty {
            errorf!(r, "{} failed jfif type test", test.path);
            continue;
        }
        infof!(
            r,
            "\nJpegIdentification: {} [{} x {}]\n",
            test.path,
            info.size.width,
            info.size.height
        );
    }

    // Test several malformed jpegs.
    let mut info = JfifInfo {
        size: ISize::new(0, 0),
        ty: JfifType::Grayscale,
    };
    {
        let good_jpeg_length = 659;
        let data = &GOOD_JPEG[..good_jpeg_length];
        reporter_assert!(r, is_jfif(Some(data), Some(&mut info)));
        reporter_assert!(r, info.size == ISize::new(8, 8));
        reporter_assert!(r, info.ty == JfifType::YCbCr);

        // Not long enough to read first (SOI) segment marker.
        reporter_assert!(r, !is_jfif(Some(&GOOD_JPEG[..1]), Some(&mut info)));

        // Not long enough to read second segment (APP0) marker.
        reporter_assert!(r, !is_jfif(Some(&GOOD_JPEG[..3]), Some(&mut info)));

        // Not long enough to read second segment's length.
        reporter_assert!(r, !is_jfif(Some(&GOOD_JPEG[..5]), Some(&mut info)));

        // APP0 segment is truncated.
        reporter_assert!(r, !is_jfif(Some(&GOOD_JPEG[..7]), Some(&mut info)));

        // Missing SOF segment.
        reporter_assert!(r, !is_jfif(Some(&GOOD_JPEG[..89]), Some(&mut info)));
    }
    {
        // JFIF tag missing.
        let jpeg_length = 177;
        reporter_assert!(
            r,
            !is_jfif(Some(&JPEG_JFIF_TAG_MISSING[..jpeg_length]), Some(&mut info))
        );
    }
    {
        // APP0 segment short (byte 6 changed).
        let jpeg_length = 177;
        reporter_assert!(
            r,
            !is_jfif(Some(&JPEG_APP0_SHORT[..jpeg_length]), Some(&mut info))
        );
    }
    {
        // SOF segment short. ('\21' replaced with '\5')
        let jpeg_length = 177;
        reporter_assert!(
            r,
            !is_jfif(Some(&JPEG_SOF_SHORT[..jpeg_length]), Some(&mut info))
        );
    }
    {
        // Unsupported 12-bit components. ('\10' replaced with '\14')
        let jpeg_length = 177;
        reporter_assert!(
            r,
            !is_jfif(Some(&JPEG_12_BIT[..jpeg_length]), Some(&mut info))
        );
    }
    {
        // Two color channels.  ('\3' replaced with '\2')
        let jpeg_length = 177;
        reporter_assert!(
            r,
            !is_jfif(Some(&JPEG_TWO_CHANNELS[..jpeg_length]), Some(&mut info))
        );
    }
});
