#[allow(clippy::too_many_arguments)] // mirrors the C++ template's parameters
fn create_runtime_combos<T: Clone>(
    reporter: &mut Reporter,
    effect_factory: impl Fn(&str) -> Result<RuntimeEffect, String>,
    precompile_factory: impl Fn(RuntimeEffect, &[Vec<Option<PrecompileBaseHandle>>]) -> Option<T>,
    wrap: fn(T) -> PrecompileBaseHandle,
    red_code: &str,
    green_code: &str,
    blue_code: &str,
    combine_code: &str,
) -> Option<T> {
    let red_effect = effect_factory(red_code);
    reporter_assert!(
        reporter,
        red_effect.is_ok(),
        "{}",
        red_effect.as_ref().err().map_or("", String::as_str)
    );
    let green_effect = effect_factory(green_code);
    reporter_assert!(
        reporter,
        green_effect.is_ok(),
        "{}",
        green_effect.as_ref().err().map_or("", String::as_str)
    );
    let blue_effect = effect_factory(blue_code);
    reporter_assert!(
        reporter,
        blue_effect.is_ok(),
        "{}",
        blue_effect.as_ref().err().map_or("", String::as_str)
    );
    let combine_effect = effect_factory(combine_code);
    reporter_assert!(
        reporter,
        combine_effect.is_ok(),
        "{}",
        combine_effect.as_ref().err().map_or("", String::as_str)
    );

    let red = precompile_factory(red_effect.expect("red effect"), &[]);
    reporter_assert!(reporter, red.is_some());
    let green = precompile_factory(green_effect.expect("green effect"), &[]);
    reporter_assert!(reporter, green.is_some());
    let blue = precompile_factory(blue_effect.expect("blue effect"), &[]);
    reporter_assert!(reporter, blue.is_some());

    let (red, green, blue) = (red?, green?, blue?);
    let combine = precompile_factory(
        combine_effect.expect("combine effect"),
        &[
            vec![Some(wrap(red)), Some(wrap(green))],
            vec![Some(wrap(blue)), None],
        ],
    );
    reporter_assert!(reporter, combine.is_some());
    combine
}

// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L254-L345 (chrome/m156)
fn runtime_effect_test(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    reporter: &mut Reporter,
) {
    // paintOptions (64 = 4*4*4)
    //  |- combineShader (4)
    //  |       0: redShader  | greenShader
    //  |       1: blueShader | nullptr
    //  |
    //  |- combineColorFilter (4)
    //  |       0: redColorFilter  | greenColorFilter
    //  |       1: blueColorFilter | nullptr
    //  |
    //  |- combineBlender (4)
    //  |       0: redBlender  | greenBlender
    //  |       1: blueBlender | nullptr

    let mut paint_options = PaintOptions::new();

    // shaders
    {
        const RED_S: &str = "
            half4 main(vec2 fragcoord) { return half4(.5, 0, 0, .5); }
        ";
        const GREEN_S: &str = "
            half4 main(vec2 fragcoord) { return half4(0, .5, 0, .5); }
        ";
        const BLUE_S: &str = "
            half4 main(vec2 fragcoord) { return half4(0, 0, .5, .5); }
        ";
        const COMBINE_S: &str = "
            uniform shader first;
            uniform shader second;
            half4 main(vec2 fragcoords) {
                return first.eval(fragcoords) + second.eval(fragcoords);
            }
        ";
        let combination = create_runtime_combos::<PrecompileShader>(
            reporter,
            |code| RuntimeEffect::make_for_shader(code, None),
            PrecompileRuntimeEffects::make_precompile_shader,
            PrecompileBaseHandle::Shader,
            RED_S,
            GREEN_S,
            BLUE_S,
            COMBINE_S,
        );
        paint_options.set_shaders(&combination.into_iter().collect::<Vec<_>>());
    }

    // color filters
    {
        const RED_CF: &str = "
            half4 main(half4 color) { return half4(.5, 0, 0, .5); }
        ";
        const GREEN_CF: &str = "
            half4 main(half4 color) { return half4(0, .5, 0, .5); }
        ";
        const BLUE_CF: &str = "
            half4 main(half4 color) { return half4(0, 0, .5, .5); }
        ";
        const COMBINE_CF: &str = "
            uniform colorFilter first;
            uniform colorFilter second;
            half4 main(half4 color) { return first.eval(color) + second.eval(color); }
        ";
        let combination = create_runtime_combos::<PrecompileColorFilter>(
            reporter,
            |code| RuntimeEffect::make_for_color_filter(code, None),
            PrecompileRuntimeEffects::make_precompile_color_filter,
            PrecompileBaseHandle::ColorFilter,
            RED_CF,
            GREEN_CF,
            BLUE_CF,
            COMBINE_CF,
        );
        paint_options.set_color_filters(&[combination]);
    }

    // blenders
    {
        const RED_B: &str = "
            half4 main(half4 src, half4 dst) { return half4(.5, 0, 0, .5); }
        ";
        const GREEN_B: &str = "
            half4 main(half4 src, half4 dst) { return half4(0, .5, 0, .5); }
        ";
        const BLUE_B: &str = "
            half4 main(half4 src, half4 dst) { return half4(0, 0, .5, .5); }
        ";
        const COMBINE_B: &str = "
            uniform blender first;
            uniform blender second;
            half4 main(half4 src, half4 dst) {
                return first.eval(src, dst) + second.eval(src, dst);
            }
        ";
        let combination = create_runtime_combos(
            reporter,
            |code| RuntimeEffect::make_for_blender(code, None),
            PrecompileRuntimeEffects::make_precompile_blender,
            PrecompileBaseHandle::Blender,
            RED_B,
            GREEN_B,
            BLUE_B,
            COMBINE_B,
        );
        paint_options.set_blenders(&combination.into_iter().collect::<Vec<_>>());
    }

    reporter_assert!(reporter, paint_options.num_combinations() == 64);

    let precompile_ids = collect_precompile_ids(&paint_options, key_context, render_pass_desc);
    assert_count(&precompile_ids, 64);
}

