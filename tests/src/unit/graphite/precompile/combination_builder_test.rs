/// The IDs `buildCombinations` reports, in order (the test's `precompileIDs` vector).
fn collect_precompile_ids(
    paint_options: &PaintOptions,
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
) -> Vec<UniquePaintParamsID> {
    let precompile_ids = RefCell::new(Vec::new());
    paint_options.build_combinations(
        key_context,
        DrawTypeFlags::NONE,
        /* with_primitive_blender= */ false,
        Coverage::None,
        render_pass_desc,
        &|id, _, _, _, _| precompile_ids.borrow_mut().push(id),
    );
    precompile_ids.into_inner()
}

/// `SkASSERT(precompileIDs.size() == expected)`.
fn assert_count(precompile_ids: &[UniquePaintParamsID], expected: i32) {
    assert_eq!(i32::try_from(precompile_ids.len()).unwrap_or(-1), expected);
}

// A default kSrcOver blend mode will be supplied if no other blend options are added
// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L43-L63 (chrome/m156)
fn no_blend_mode_option_test(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    _reporter: &mut Reporter,
) {
    let mut paint_options = PaintOptions::new();
    paint_options.set_shaders(&[PrecompileShaders::color()]);

    assert_eq!(
        paint_options.num_combinations(),
        EXPECTED_SOLID_COLOR_COMBOS
    );

    let precompile_ids = collect_precompile_ids(&paint_options, key_context, render_pass_desc);
    assert_count(&precompile_ids, EXPECTED_SOLID_COLOR_COMBOS);
}

// This test checks that the 'PaintOptions::numCombinations' method and the number actually
// generated by 'buildCombinations' agree with the expected number of combinations.
// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L65-L94 (chrome/m156)
fn run_test(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    reporter: &mut Reporter,
    paint_options: &PaintOptions,
    expected_num_options: i32,
) {
    reporter_assert!(
        reporter,
        paint_options.num_combinations() == expected_num_options,
        "expected {}, but was {}",
        expected_num_options,
        paint_options.num_combinations()
    );

    // Some combinations produced may result in the same UniquePaintParamsID since the
    // combinatorics introduce opaque vs. non-opaque branches. Depending on how that recombines
    // in the final paint key, key-impacting decisions may or may not be made. In most cases, the
    // number of unique paint IDs will be lower than the raw number of combinations. Since we
    // don't de-dupe when adding to `precompileIDs` here, we can assert the total is
    // `expectedNumOptions`.
    let precompile_ids = collect_precompile_ids(paint_options, key_context, render_pass_desc);
    assert_count(&precompile_ids, expected_num_options);
}

// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L96-L165 (chrome/m156)
fn big_test(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    reporter: &mut Reporter,
) {
    const NUM_EXPECTED: i32 = 6360;
    // paintOptions (6360 = 4*1590)
    //  |- (1590 = 6+1584) sweepGrad_0 (3*2) |
    //  |                blendShader_0 (1584 = 1*8*198)
    //  |                 |- 0: (1)       kSrc (1)
    //  |                 |- 1: (8=6+2)   (dsts) linearGrad_0 (3*2) | solid_0 (2)
    //  |                 |- 2: (198=6+192) (srcs) linearGrad_1 (3*2) |
    //  |                                        blendShader_1 (192=1*8*24)
    //  |                                         |- 0: (1) kDst (1)
    //  |                                         |- 1: (8=6+2) (dsts) radGrad_0 (3*2) | solid_1 (2)
    //  |                                         |- 2: (24) (srcs) imageShader_0 (24)
    //  |
    //  |- (4) 4-built-in-blend-modes

    let mut paint_options = PaintOptions::new();

    // first, shaders. First top-level option (sweepGrad_0)
    let sweep_grad_0 =
        PrecompileShaders::sweep_gradient(GradientShaderFlags::ALL, Interpolation::default());

    let block_modes = [BlendMode::Src];

    let more_blend_modes = [BlendMode::Dst];

    // Second top-level option (blendShader_0)
    let blend_shader_0 = PrecompileShaders::blend_modes(
        &block_modes,
        &[
            PrecompileShaders::linear_gradient(GradientShaderFlags::ALL, Interpolation::default()),
            PrecompileShaders::color(),
        ],
        &[
            PrecompileShaders::linear_gradient(GradientShaderFlags::ALL, Interpolation::default()),
            PrecompileShaders::blend_modes(
                &more_blend_modes,
                &[
                    PrecompileShaders::radial_gradient(
                        GradientShaderFlags::ALL,
                        Interpolation::default(),
                    ),
                    PrecompileShaders::color(),
                ],
                &[PrecompileShaders::image(
                    ImageShaderFlags::ALL,
                    &[],
                    &ALL_TILE_MODES,
                )],
            ),
        ],
    );
    paint_options.set_shaders(&[sweep_grad_0, blend_shader_0]);

    let even_more_blend_modes = [
        BlendMode::SrcOver,
        BlendMode::Src,
        BlendMode::DstOver,
        BlendMode::Dst,
    ];

    // now, blend modes
    paint_options.set_blend_modes(&even_more_blend_modes); // c array
    reporter_assert!(
        reporter,
        paint_options.num_combinations() == NUM_EXPECTED,
        "Actual # of combinations {}, expected {}",
        paint_options.num_combinations(),
        NUM_EXPECTED
    );

    let precompile_ids = collect_precompile_ids(&paint_options, key_context, render_pass_desc);
    assert_count(&precompile_ids, NUM_EXPECTED);
}

