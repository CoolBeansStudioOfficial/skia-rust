// Exercise all the PrecompileShaders factories
// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L377-L521 (chrome/m156)
#[allow(clippy::too_many_lines)] // mirrors the C++ test, one block per factory
fn shader_subtest(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    reporter: &mut Reporter,
) {
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::empty()]);
        run_test(key_context, render_pass_desc, reporter, &paint_options, 1);
    }
    // The solid color shader only ever generates one combination. Because it is constant
    // everywhere it can cause other shaders to be elided (e.g., the LocalMatrix shader -
    // see the LocalMatrix test(s) below).
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::color()]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_SOLID_COLOR_COMBOS,
        );
    }
    // In general, the blend shader generates the product of the options in each of its slots.
    // The rules for how many combinations the SkBlendModes yield are:
    //   all Porter-Duff SkBlendModes collapse to one option (see GetPorterDuffBlendConstants))
    //   all HSCL SkBlendModes collapse to another option
    //   all other SkBlendModes produce unique options
    {
        let blend_modes = [
            BlendMode::SrcOut,  // Porter-Duff
            BlendMode::SrcOver, // Porter-Duff
            BlendMode::Hue,     // HSLC
            BlendMode::Color,   // HSLC
            BlendMode::Screen,  // Fixed Screen
            BlendMode::Darken,  // fixed Darken
        ];
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::blend_modes(
            &blend_modes,
            &[PrecompileShaders::color()],
            &[PrecompileShaders::make_fractal_noise()],
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            // Porter-Duff, HSLC, Screen, Darken
            4 * EXPECTED_SOLID_COLOR_COMBOS * EXPECTED_PERLIN_NOISE_COMBOS,
        );
    }
    // The ImageShaders have 24 combinations
    // (6 sampling/tiling x 4 color space xform)
    // The CoordClamp shader doesn't add any additional combinations to its wrapped shader.
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::coord_clamp(&[PrecompileShaders::image(
            ImageShaderFlags::ALL,
            &[],
            &ALL_TILE_MODES,
        )])]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_IMAGE_COMBOS,
        );
    }
    // RawImageShaders only have 10 combinations since they never do cubic filtering and only have
    // two possible color space xform variants.
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::raw_image(
            ImageShaderFlags::EXCLUDE_CUBIC,
            &[],
            &ALL_TILE_MODES,
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_RAW_IMAGE_COMBOS,
        );
    }
    // Each Perlin noise shader only has one combination
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[
            PrecompileShaders::make_fractal_noise(),
            PrecompileShaders::make_turbulence(),
        ]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_PERLIN_NOISE_COMBOS + EXPECTED_PERLIN_NOISE_COMBOS,
        );
    }
    // Each gradient shader generates 3 combinations x 2 opacities
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[
            PrecompileShaders::linear_gradient(GradientShaderFlags::ALL, Interpolation::default()),
            PrecompileShaders::radial_gradient(GradientShaderFlags::ALL, Interpolation::default()),
            PrecompileShaders::two_point_conical_gradient(
                GradientShaderFlags::ALL,
                Interpolation::default(),
            ),
            PrecompileShaders::sweep_gradient(GradientShaderFlags::ALL, Interpolation::default()),
        ]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_GRADIENT_COMBOS * 4,
        );
    }
    // Each picture shader generates 48 combinations:
    //    2 (pictureShader LM) x 24 (imageShader variations)
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::picture()]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_PICTURE_COMBOS,
        );
    }
    // In general, the local matrix shader just generates however many options its wrapped
    // shader generates.
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::local_matrix(
            &[PrecompileShaders::linear_gradient(
                GradientShaderFlags::ALL,
                Interpolation::default(),
            )],
            false,
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_GRADIENT_COMBOS,
        );
    }
    // The ColorFilter shader just creates the cross product of its child options
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::color_filter(
            &[PrecompileShaders::linear_gradient(
                GradientShaderFlags::ALL,
                Interpolation::default(),
            )],
            &[PrecompileColorFilters::blend()],
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_GRADIENT_COMBOS * EXPECTED_BLEND_CF_COMBOS,
        );
    }
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_shaders(&[PrecompileShaders::working_color_space(
            &[PrecompileShaders::linear_gradient(
                GradientShaderFlags::ALL,
                Interpolation::default(),
            )],
            &[ColorSpace::new_srgb_linear()],
            &[],
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_GRADIENT_COMBOS, // only one colorSpace
        );
    }
}

// Exercise all the PrecompileColorFilters factories. The impact of colorfilters on the number
// of combinations is very predictable. Except for the Compose and Lerp color filters, all the
// color filters only ever have one combination. The Compose and Lerp color filters also just
// simply generate the cross product of their children.
// Port of: tests/graphite/precompile/CombinationBuilderTest.cpp#L523-L592 (chrome/m156)
fn colorfilter_subtest(
    key_context: &KeyContext<'_>,
    render_pass_desc: &RenderPassDesc,
    reporter: &mut Reporter,
) {
    {
        // The compose colorfilter just generates the cross product of its children.
        let expected_num_options = EXPECTED_TABLE_CF_COMBOS
            * (EXPECTED_HIGH_CONTRAST_CF_COMBOS + EXPECTED_LUMA_CF_COMBOS)
            + EXPECTED_LIGHTING_CF_COMBOS
                * (EXPECTED_HIGH_CONTRAST_CF_COMBOS + EXPECTED_LUMA_CF_COMBOS);
        let mut paint_options = PaintOptions::new();
        paint_options.set_color_filters(&[PrecompileColorFilters::compose(
            &[
                Some(PrecompileColorFilters::table()),
                Some(PrecompileColorFilters::lighting()),
            ],
            &[
                PrecompileColorFilters::high_contrast(),
                PrecompileColorFilters::luma(),
            ],
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            expected_num_options,
        );
    }
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_color_filters(&[Some(PrecompileColorFilters::blend())]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_BLEND_CF_COMBOS,
        );
    }
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_color_filters(&[
            Some(PrecompileColorFilters::matrix(true)),
            Some(PrecompileColorFilters::hsla_matrix()),
        ]);
        // HSLAMatrix and Matrix map to the same color filter
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_MATRIX_CF_COMBOS + EXPECTED_MATRIX_CF_COMBOS,
        );
    }
    {
        let mut paint_options = PaintOptions::new();
        paint_options.set_color_filters(&[
            Some(PrecompileColorFilters::linear_to_srgb_gamma()),
            Some(PrecompileColorFilters::srgb_to_linear_gamma()),
        ]);
        // LinearToSRGB and SRGBToLinear both map to the colorspace colorfilter
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            EXPECTED_COLOR_SPACE_CF_COMBOS + EXPECTED_COLOR_SPACE_CF_COMBOS,
        );
    }
    {
        // The lerp colorfilter just generates the cross product of its children.
        let expected_num_options = EXPECTED_MATRIX_CF_COMBOS
            * (EXPECTED_BLEND_CF_COMBOS + EXPECTED_OVERDRAW_CF_COMBOS)
            + EXPECTED_LUMA_CF_COMBOS * (EXPECTED_BLEND_CF_COMBOS + EXPECTED_OVERDRAW_CF_COMBOS);
        let mut paint_options = PaintOptions::new();
        paint_options.set_color_filters(&[PrecompileColorFilters::lerp(
            &[
                Some(PrecompileColorFilters::matrix(true)),
                PrecompileColorFilters::luma(),
            ],
            &[
                Some(PrecompileColorFilters::blend()),
                PrecompileColorFilters::overdraw(),
            ],
        )]);
        run_test(
            key_context,
            render_pass_desc,
            reporter,
            &paint_options,
            expected_num_options,
        );
    }
}

