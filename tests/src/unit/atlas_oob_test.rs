// Port of: tests/AtlasOobTest.cpp#L141-L172 (chrome/m156)
fn run_atlas_oob_test(reporter: &mut Reporter, canvas: &Canvas) {
    let discardable_manager = Arc::new(FakeDiscardableManager);
    let mut client = StrikeClient::new(discardable_manager, false, None);

    // 1. Prepare Strike Data
    if !client.read_strike_data(&STRIKE_DATA) {
        reporter_assert!(reporter, false, "Failed to read initial strike data");
    }

    // 2. Prepare and Execute DrawSlug ops
    let paint = Paint::default();
    let mut draw_slug_op = DRAW_SLUG_OP;
    for idx in 0..1 {
        //    for idx in 0..2 {
        if idx == 0 {
            draw_slug_op[0x48] = MaskFormat::Argb as u8;
        } else if idx == 1 {
            draw_slug_op[0x48] = MaskFormat::A8 as u8;
        }
        draw_slug_op[0xd8] = SkMaskFormat::Argb32 as u8;
        draw_slug_op[0xe0] = 0x99;

        let slug = client.deserialize_slug_for_test(&draw_slug_op);
        if let Some(slug) = slug {
            canvas.draw_slug(Some(&slug), &paint);
        }
    }
}

