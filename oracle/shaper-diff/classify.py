"""Regenerates oracle/shaper-diff/known-divergences.txt (docs/design/modules.md §2.4).

    python3 -I oracle/shaper-diff/classify.py <shaper_diff driver> <shaper-diff rust binary> <fonts dir> <tables dir>

For every row where HarfRust (the Rust binary) differs from the stored HarfBuzz result in
expected/*.txt, it dumps both sides line by line and classifies the row by the worst kind of
difference among its lines:

  glyphs      a glyph id, a cluster or the glyph count differs
  advance-1   only advances differ, by at most 1
  offset      only offsets differ by more than 1
  offset-1    only offsets differ, by at most 1

and names the class (see the header of known-divergences.txt for what each means). The classes were
root-caused by reading the two sources, not inferred from the numbers.
"""
import collections
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = {"builtin": "a", "skia-funcs": "b", "empty-face": "c"}

HEADER = """\
# Rows where HarfRust 0.9.0 differs from HarfBuzz 9cb1fee5: `config font source class`.
# Every other row is exact. A row listed here that starts matching, or a row that differs and is
# not listed, fails the replay test. Generated by classify.py. Classes (docs/design/modules.md §2.4):
#   fallback-mark-gap         y offset of fallback-positioned marks: HarfBuzz hb-ot-shape-fallback.cc#L220
#                             uses font->y_scale / 16, HarfRust scales (units_per_em / 16).
#   anchor-rounding           +-1 in GPOS mark anchor offsets: HarfBuzz 13.1 rounds the difference of the
#                             float-scaled anchors (MarkArray.hh#L57), HarfRust scales the difference.
#   arabic-fallback-shaping   fonts with no Arabic GSUB: HarfBuzz substitutes presentation forms
#                             (hb-ot-shaper-arabic-fallback.hh); HarfRust's arabic_fallback_shape is a stub.
#   builtin-extents           mode a only: the built-in glyph extents of HarfRust are missing where HarfBuzz has them
#                             (e.g. CFF fonts), so fallback marks get offset 0 instead of an extents-based one;
#                             Skia's extents callback replaces them, and mode b shows fallback-mark-gap instead.
#   builtin-advance-rounding  +-1 in 16.16 advances of the built-in font functions (mode a only; Skia's
#                             callbacks replace them, so mode b has none).
"""


def classify_line(c, r):
    gc = c.split(" ") if c else []
    gr = r.split(" ") if r else []
    if len(gc) != len(gr):
        return "glyphs"
    worst = None
    advance = False
    for p, q in zip(gc, gr):
        a = [int(x) for x in p.split(":")]
        b = [int(x) for x in q.split(":")]
        if a[0] != b[0] or a[1] != b[1]:
            return "glyphs"
        if a[2:4] != b[2:4]:
            advance = True
            worst = max(worst or 0, max(abs(a[2] - b[2]), abs(a[3] - b[3])))
        elif a[4:] != b[4:]:
            if not advance:
                worst = max(worst or 0, max(abs(a[4] - b[4]), abs(a[5] - b[5])))
    if worst is None:
        return None
    if advance:
        return "advance-1" if worst == 1 else "advance"
    return "offset-1" if worst == 1 else "offset"


def parse_dump(text):
    d = {}
    for line in text.split("\n"):
        if line.startswith("L "):
            parts = line.split(" ", 5)
            d[(parts[3], int(parts[4]))] = parts[5] if len(parts) > 5 else ""
    return d


def main():
    driver, rust, fonts, tables = sys.argv[1:5]
    env = dict(os.environ, SKIA_RUST_SHAPER_DIFF_FONTS=fonts, SHAPER_DIFF_DUMP="1")
    known = []
    for f, mode in FILES.items():
        def rows(path):
            return {tuple(l.split()[:3]): l.split()[3:] for l in open(path) if not l.startswith("#")}
        expected = rows(os.path.join(HERE, "expected", f + ".txt"))
        plain = dict(env)
        plain.pop("SHAPER_DIFF_DUMP")
        out = subprocess.run([rust, "run", mode], capture_output=True, text=True, env=plain).stdout
        got = {tuple(l.split()[:3]): l.split()[3:] for l in out.split("\n") if l and not l.startswith("L ")}
        pairs = sorted({(k[0], k[1]) for k in expected if expected[k] != got.get(k)})
        for cfg, font in pairs:
            cd = subprocess.run(
                [driver, "--fonts", fonts, "--font-list", os.path.join(HERE, "fonts.txt"),
                 "--configs", os.path.join(HERE, "configs.txt"), "--corpus", os.path.join(HERE, "corpus"),
                 "--tables", tables, "--config", cfg, "--font", font, "--dump"],
                capture_output=True, text=True).stdout
            rd = subprocess.run([rust, "run", mode, "--config", cfg, "--font", font],
                                capture_output=True, text=True, env=env).stdout
            dc, dr = parse_dump(cd), parse_dump(rd)
            per = collections.defaultdict(set)
            for k in dc:
                kind = classify_line(dc[k], dr.get(k, ""))
                if kind:
                    per[k[0]].add(kind)
            for src, kinds in per.items():
                for kind in ("glyphs", "advance", "advance-1", "offset", "offset-1"):
                    if kind in kinds:
                        name = {
                            "glyphs": "arabic-fallback-shaping",
                            "advance": "builtin-advance-rounding",
                            "advance-1": "builtin-advance-rounding",
                            "offset": "builtin-extents" if f == "builtin" else "fallback-mark-gap",
                            "offset-1": "anchor-rounding",
                        }[kind]
                        known.append(f"{cfg} {font} {src} {name}")
                        break
    known.sort()
    with open(os.path.join(HERE, "known-divergences.txt"), "w", newline="\n") as out:
        out.write(HEADER)
        for k in known:
            out.write(k + "\n")
    print(collections.Counter(k.split()[-1] for k in known))


main()
