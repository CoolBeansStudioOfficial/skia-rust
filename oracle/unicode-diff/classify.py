r"""Regenerates oracle/unicode-diff/known-divergences.txt (docs/design/modules.md §2.5 and §3.4).

    python3 -I oracle/unicode-diff/classify.py <unicode_diff driver> <unicode-diff rust binary> <icudtl.dat> <ucd dir>

For every divergence between ICU (the stored results in expected/*.txt) and the Rust twin, it
looks at the detail of both sides (the drivers' --dump output) and assigns a class to each place
where they differ: a boundary the engines disagree on, a rule status, a bidi level, a conformance
line. A string with several kinds of differences gets all of their classes (`a+b`). The classes were
root-caused by reading the sources (see the header of known-divergences.txt), not inferred from
numbers; anything the rules below do not explain is written as `unclassified` and fails review.

It also prints, per class, how many strings, boundaries and conformance lines it covers (the table
of docs/design/modules.md §3.4).
"""
import collections
import os
import subprocess
import sys
import unicodedata

UNCLASSIFIED = []
HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS = os.path.join(HERE, "corpus")

HEADER = r"""# Divergences between the Rust twin (skia_rust_unicode::icu_shim: breaks on ICU's engine, ported, over Chromium's
# compiled break data; properties, case and locales on ICU4X =2.3.0 compiled data; unicode-bidi =0.3.18 for bidi) and
# Chromium ICU 78.2 (d578f2e8): `<key> <class>[+<class>...]`. Every other row, range and conformance line is exact.
# A listed entry that starts matching, or a divergence that is not listed, fails the replay test.
# Generated by classify.py (docs/design/modules.md §3.4-§3.6). Keys: `<case> <source> <index>` for a string,
# `prop|cp <name> <first>-<last> <icu>/<icu4x>` for a range of code points, `conf <file> <line> icu-only|icu4x-only`
# for a conformance-test line that only one engine fails, `misc <call>` for a misc line.
#
# M2 emulated what ICU4X does not report (rule status, navigation, numbering, locales); M4 replaced ICU4X's
# segmenters with a port of ICU's RuleBasedBreakIterator and dictionary engines over the rule tables and
# dictionaries of Chromium's icudtl.dat (skia-rust-unicode-data). The break classes of M0c and M2 are gone
# (word-dot, word-colon, word-hangul-syllable-jamo, word-dictionary-cj, word-dictionary-sa, line-dictionary-sa,
# line-normal-other, icu4x-lb-<rule>); classify.py still knows them, for measuring an ICU4X data source
# (icu_shim::CompiledData). What is left is bidi (M3). Classes:
#
# Bidi (UAX #9)
#   bidi-direction              ubidi_getDirection is directionFromFlags (ubidi.cpp#L1007-L1020): it follows which strong
#                               types occur in the text (LTR when there is no R, AL, RLE, RLO or RLI), adjusted for the
#                               paragraph level (MIXED for RTL text in an LTR paragraph), not the resolved levels the
#                               twin derives it from.
#   bidi-uniform-direction-shortcut  when directionFromFlags is LTR or RTL, ICU does not resolve the text: every level
#                               is the paragraph level, whatever explicit embeddings, overrides or isolates the text
#                               contains; unicode-bidi applies them (U+202D abc: ICU 0 0 0 0, unicode-bidi 0 2 2 2).
#   bidi-x9-removed-levels      the level of characters rule X9 removes (LRE, RLE, LRO, RLO, PDF, BN): ICU gives an
#                               opening character the level it opens and a closing one the outer level;
#                               unicode-bidi gives them the previous character's level.
#   bidi-isolate-levels         levels of isolate initiators and PDI.
#   bidi-default-level-number-after-separator  UBIDI_DEFAULT_RTL: a number after an empty paragraph (`\n\n2 abc`)
#                               gets level 2 in ICU (as if the last strong direction were R), 0 in unicode-bidi (W7).
#   bidi-levels-other           any other level difference.
# Conformance files
#   icu-bidi-conformance        BidiCharacterTest.txt lines that ICU fails and the twin passes.
"""

# ---- character helpers ----------------------------------------------------------------------------


def in_ranges(cp, ranges):
    return any(a <= cp <= b for a, b in ranges)


SA = [(0x0E00, 0x0EFF), (0x1000, 0x109F), (0xA9E0, 0xA9FF), (0xAA60, 0xAA7F), (0x1780, 0x17FF),
      (0x19E0, 0x19FF), (0x1980, 0x19DF), (0x1A20, 0x1AAF), (0x200B, 0x200B)]
CJ = [(0x2E80, 0x2FDF), (0x3000, 0x30FF), (0x31F0, 0x31FF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
      (0xF900, 0xFAFF), (0xFF00, 0xFFEF), (0x20000, 0x323AF)]


# ---- corpus ----------------------------------------------------------------------------------------


def unescape(line):
    out = []
    i = 0
    while i < len(line):
        c = line[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        e = line[i + 1]
        if e == "n":
            out.append("\n"); i += 2
        elif e == "r":
            out.append("\r"); i += 2
        elif e == "t":
            out.append("\t"); i += 2
        elif e == "\\":
            out.append("\\"); i += 2
        elif e == "x":
            out.append(chr(int(line[i + 2:i + 4], 16))); i += 4
        elif e == "u":
            out.append(chr(int(line[i + 2:i + 6], 16))); i += 6
        elif e == "U":
            out.append(chr(int(line[i + 2:i + 10], 16))); i += 10
        else:
            raise ValueError(line)
    return "".join(out)


def load_corpus():
    strings = {}
    for l in open(os.path.join(CORPUS, "index.txt"), encoding="utf-8"):
        if l.startswith("#") or not l.strip():
            continue
        name, kind = l.split()
        text = open(os.path.join(CORPUS, name), encoding="utf-8", newline="").read()
        sid = name[:-4]
        if kind == "whole":
            strings[(sid, 0)] = text
        else:
            for i, line in enumerate(text.split("\n")[:-1]):
                strings[(sid, i)] = unescape(line)
    return strings


# ---- running the two sides ---------------------------------------------------------------------------


def load_dump(text):
    d = {}
    for l in text.splitlines():
        a = l.split(" ", 3)
        d[(a[0], a[1], int(a[2]))] = a[3] if len(a) > 3 else ""
    return d


def parse_breaks(s):
    out = {}
    for t in s.split():
        p, st = t.split(":")
        out[int(p)] = int(st)
    return out


def offsets(text, u8):
    m = {}
    o = 0
    for i, ch in enumerate(text):
        m[o] = i
        o += len(ch.encode("utf-8")) if u8 else (2 if ord(ch) > 0xFFFF else 1)
    m[o] = len(text)
    return m


# ---- classification of boundaries --------------------------------------------------------------------


def word_position_class(kind, prev, nxt):
    ctx = [c for c in (prev, nxt) if c is not None]
    if any(c in (0x2E, 0xFF0E) for c in ctx):
        return "word-dot"
    if any(c in (0x3A, 0xFE13, 0xFE55, 0xFF1A) for c in ctx):
        return "word-colon"
    if any(0xAC00 <= c <= 0xD7A3 for c in ctx) and any(0x1100 <= c <= 0x11FF for c in ctx):
        return "word-hangul-syllable-jamo"
    if any(in_ranges(c, SA) for c in ctx):
        return "word-dictionary-sa"
    if any(in_ranges(c, CJ) for c in ctx):
        return "word-dictionary-cj"
    return "unclassified"


def word_status_class(a, b, prev):
    # The shim runs Chromium's word.txt for the rule status (M2): at a boundary both sides have, the
    # status is ICU's.
    return "unclassified"


def line_position_class(kind, prev, nxt):
    ctx = [c for c in (prev, nxt) if c is not None]
    if any(in_ranges(c, SA) for c in ctx):
        return "line-dictionary-sa"
    return "line-normal-other"


def classify_breaks(case, text, a, b):
    """Classes (with counts) for one string of a breaks case: a and b are {position: status}."""
    kind = case.split("-")[0]
    u8 = case.endswith("u8")
    om = offsets(text, u8)
    cps = [ord(c) for c in text]
    out = collections.Counter()
    for p in sorted(set(a) | set(b)):
        i = om.get(p)
        prev = cps[i - 1] if i is not None and i > 0 else None
        nxt = cps[i] if i is not None and i < len(cps) else None
        if p in a and p in b:
            if a[p] == b[p]:
                continue
            # Line and sentence status are exact since M2 (the shim's rule-status emulation).
            c = word_status_class(a[p], b[p], prev) if kind == "word" else "unclassified"
        else:
            if kind == "word":
                c = word_position_class(kind, prev, nxt)
            elif kind == "line":
                c = line_position_class(kind, prev, nxt)
            else:
                c = "unclassified"
        if c in ("unclassified", "line-normal-other"):
            UNCLASSIFIED.append((case, kind, a.get(p), b.get(p), p, prev, nxt))
        out[c] += 1
    return out


def expand_levels(s):
    parts = dict(kv.split("=", 1) for kv in s.split(" "))
    levels = []
    if parts["levels"]:
        for run in parts["levels"].split(","):
            lv, n = run.split("*")
            levels += [int(lv)] * int(n)
    return int(parts["dir"]), int(parts["len"]), levels


def utf16_chars(text):
    out = []
    for ch in text:
        out.append(ord(ch))
        if ord(ch) > 0xFFFF:
            out.append(None)  # low surrogate
    return out


def classify_bidi(case, text, a, b):
    out = collections.Counter()
    if a.startswith("setpara-error") or b.startswith("setpara-error") or "error" in a + b:
        out["unclassified"] += 1
        return out
    da, la, lva = expand_levels(a)
    db, lb, lvb = expand_levels(b)
    if la != lb:
        out["unclassified"] += 1
        return out
    units = utf16_chars(text)
    # ICU skips the resolution of text without any character of the opposite direction (modules.md
    # §3.4): one uniform level, the explicit embeddings and isolates it contains having no effect.
    shortcut = len(set(lva)) == 1 and len(set(lvb)) > 1
    for i, (x, y) in enumerate(zip(lva, lvb)):
        if x == y:
            continue
        cp = units[i] if i < len(units) else None
        if cp is None:
            cp = units[i - 1]
        bc = unicodedata.bidirectional(chr(cp))
        if shortcut:
            out["bidi-uniform-direction-shortcut"] += 1
        elif bc in ("LRE", "RLE", "LRO", "RLO", "PDF", "BN"):
            out["bidi-x9-removed-levels"] += 1
        elif bc in ("LRI", "RLI", "FSI", "PDI"):
            out["bidi-isolate-levels"] += 1
        elif bc in ("EN", "AN", "ES", "ET", "CS") and "auto" in case:
            out["bidi-default-level-number-after-separator"] += 1
        else:
            out["bidi-levels-other"] += 1
    if da != db and not out:
        out["bidi-direction"] += 1
    elif da != db:
        out["bidi-direction"] += 1
    return out


# ---- main ----------------------------------------------------------------------------------------------


def run(cmd):
    return subprocess.run(cmd, capture_output=True, check=True).stdout.decode("utf-8")


def main():
    driver, rust, icu_data, ucd = sys.argv[1:5]
    strings = load_corpus()
    divergences = {}
    for section in ("breaks", "bidi", "reorder", "props", "case", "conformance", "misc"):
        for l in run([rust, "divergences", section]).splitlines():
            key, icu, rs = l.split("\t")
            divergences[key] = (section, icu, rs)
    dumps = {}
    for section in ("breaks", "bidi"):
        icu = load_dump(run([driver, "--data", icu_data, "--corpus", CORPUS, "--dump", section]))
        rs = load_dump(run([rust, "run", section, "--dump"]))
        dumps[section] = (icu, rs)

    known = {}
    per_class_rows = collections.Counter()
    per_class_events = collections.Counter()
    per_class_strings = collections.defaultdict(set)
    per_case_total = collections.Counter()
    nav_source = {"nav-line-u8": "line-u8", "nav-word-u16": "word-u16"}
    for key, (section, icu_v, rs_v) in sorted(divergences.items()):
        f = key.split(" ")
        if section == "breaks":
            case, source, idx = f[0], f[1], int(f[2])
            text = strings[(source, idx)]
            icu_d, rs_d = dumps["breaks"]
            if case in nav_source:
                # Navigation is a function of the boundary positions: classify those, ignoring status.
                k2 = (nav_source[case], source, idx)
                a, b = parse_breaks(icu_d[k2]), parse_breaks(rs_d[k2])
                # The shim moves an offset inside a code point to its start as ICU does (M2), so a nav
                # row can only differ where the boundaries do; a nav row over equal boundaries stays
                # unclassified.
                classes = classify_breaks(nav_source[case], text, {p: 0 for p in a}, {p: 0 for p in b})
            else:
                classes = classify_breaks(case, text, parse_breaks(icu_d[(case, source, idx)]),
                                          parse_breaks(rs_d[(case, source, idx)]))
        elif section == "bidi":
            case, source, idx = f[0], f[1], int(f[2])
            text = strings[(source, idx)]
            icu_d, rs_d = dumps["bidi"]
            classes = classify_bidi(case, text, icu_d[(case, source, idx)], rs_d[(case, source, idx)])
        elif section == "conformance":
            file, _line, side = f[1], f[2], f[3]
            if file == "BidiCharacterTest.txt":
                classes = collections.Counter({"icu-bidi-conformance" if side == "icu-only" else "unclassified": 1})
            elif file == "WordBreakTest.txt":
                classes = collections.Counter({"word-colon" if icu_v == "fail@6.0" else "unclassified": 1})
            elif file == "LineBreakTest.txt" and side == "icu4x-only":
                classes = collections.Counter({"icu4x-lb-" + rs_v.split("@")[1]: 1})
            else:
                classes = collections.Counter({"unclassified": 1})
        else:
            classes = collections.Counter({"unclassified": 1})
        if not classes:
            classes = collections.Counter({"unclassified": 1})
        names = "+".join(sorted(classes))
        known[key] = names
        for c, n in classes.items():
            per_class_rows[c] += 1
            if section in ("breaks", "bidi") and not (f[0].endswith("u16") or f[0].startswith("nav")):
                per_class_events[c] += n
            elif section == "conformance":
                per_class_events[c] += n
            if section in ("breaks", "bidi"):
                per_class_strings[c].add((f[1], f[2]))

    with open(os.path.join(HERE, "known-divergences.txt"), "w", encoding="utf-8", newline="\n") as out:
        out.write(HEADER)
        for key in sorted(known):
            out.write(f"{key} {known[key]}\n")

    print(f"{len(known)} divergences")
    print("| Class | Distinct corpus strings | Rows | Places |")
    print("|---|---|---|---|")
    for c in sorted(per_class_rows):
        print(f"| `{c}` | {len(per_class_strings[c]) or '-'} | {per_class_rows[c]} | {per_class_events[c] or '-'} |")
    by_case = collections.Counter(k.split(" ")[0] for k in known)
    print(dict(sorted(by_case.items())))
    if os.environ.get("CLASSIFY_DEBUG"):
        agg = collections.Counter()
        for case, kind, x, y, p, prev, nxt in UNCLASSIFIED:
            agg[(case, x, y, prev if prev is None else f"{prev:04X}", nxt if nxt is None else f"{nxt:04X}")] += 1
        for k, n in agg.most_common(40):
            print(n, k)


main()
